#!/usr/bin/env node
/* Generate src/products/<product>/endpoints.gen.ts from
   docs/api-reference/<product>/endpoints.json + src/products/<product>/tool-map.json.

   - Every endpoint must land in exactly one tool (its group's tool, unless an
     operationOverride reassigns it) or the generator fails.
   - Action name = slug with '-' -> '_' (override with {action}).
   - Destructive = DELETE method or slug heuristic (override with {destructive}).
   - Summary = upstream summary minus HTTP-verb prefix (override with {summary}
     when the upstream name misdescribes the operation).
   Run: node scripts/gen-endpoint-maps.mjs   (offline; reads committed files) */
import fs from 'node:fs';

const DESTRUCTIVE_SLUG =
  /(^|-)(delete|remove|detach|cancel|refund|deactivate|reset|disconnect|regenerate)(-|$)|bulk-action|do-bulk|bulk-delete|accept-dispute|un-schedule/;

function deriveDestructive(method, slug) {
  if (method === 'GET' || method === 'HEAD') return false; // reads never gate
  if (method === 'DELETE') return true;
  return DESTRUCTIVE_SLUG.test(slug);
}

function generate(product) {
  const inventory = JSON.parse(fs.readFileSync(`docs/api-reference/${product}/endpoints.json`, 'utf8'));
  const map = JSON.parse(fs.readFileSync(`src/products/${product}/tool-map.json`, 'utf8'));

  const groupToTool = {};
  for (const [tool, def] of Object.entries(map.tools)) {
    for (const g of def.groups) {
      if (groupToTool[g]) throw new Error(`${product}: group ${g} assigned to both ${groupToTool[g]} and ${tool}`);
      groupToTool[g] = tool;
    }
  }

  const toolActions = Object.fromEntries(Object.keys(map.tools).map((t) => [t, {}]));
  const problems = [];
  const destructiveReport = [];

  for (const e of inventory.endpoints) {
    const op = `${e.group}/${e.slug}`;
    const override = map.operationOverrides[op] ?? {};
    const tool = override.tool ?? groupToTool[e.group];
    if (!tool) { problems.push(`UNASSIGNED ${op} (group ${e.group} has no tool)`); continue; }
    if (!toolActions[tool]) { problems.push(`${op} -> unknown tool ${tool}`); continue; }
    const action = override.action ?? e.slug.replace(/-/g, '_');
    if (toolActions[tool][action]) { problems.push(`COLLISION in ${tool}: action ${action} from ${op} and ${toolActions[tool][action].op}`); continue; }
    const destructive = override.destructive ?? deriveDestructive(e.method, e.slug);
    if (destructive) destructiveReport.push(`${tool}.${action} (${e.method} ${e.path})`);
    toolActions[tool][action] = {
      op,
      method: e.method,
      path: e.path,
      // Upstream summaries embed the HTTP verb ("DELETE Delete Order") — strip it.
      summary: override.summary ?? e.summary.replace(/^(GET|POST|PUT|PATCH|DELETE|HEAD)\s+/i, ''),
      destructive,
      ...(override.toolName ? { toolName: override.toolName } : {}),
      ...(override.requiredBody ? { requiredBody: override.requiredBody } : {}),
      ...(override.bodyNote ? { bodyNote: override.bodyNote } : {}),
      ...(e.path.startsWith('/?') ? { siteRoot: true } : {}),
    };
  }

  for (const [tool, actions] of Object.entries(toolActions)) {
    if (!Object.keys(actions).length) problems.push(`tool ${tool} has zero actions`);
  }
  if (problems.length) {
    console.error(`\n${product}: generation FAILED:\n  ` + problems.join('\n  '));
    process.exitCode = 1;
    return null;
  }

  const toolMeta = Object.fromEntries(
    Object.entries(map.tools).map(([name, def]) => [
      name,
      {
        description: def.description,
        ...(def.note ? { note: def.note } : {}),
        ...(def.idempotent ? { idempotent: true } : {}),
      },
    ])
  );
  let out = `/* AUTO-GENERATED by scripts/gen-endpoint-maps.mjs from docs/api-reference/${product}/endpoints.json — do not edit by hand. */\n`;
  out += `import type { EndpointDef } from '../../core/types.js';\n\n`;
  out += `export const TOOL_ENDPOINTS: Record<string, Record<string, EndpointDef>> = ${JSON.stringify(toolActions, null, 2)};\n\n`;
  out += `export const TOOL_META: Record<string, { description: string; note?: string; idempotent?: boolean }> = ${JSON.stringify(toolMeta, null, 2)};\n`;
  fs.writeFileSync(`src/products/${product}/endpoints.gen.ts`, out);

  const total = Object.values(toolActions).reduce((n, a) => n + Object.keys(a).length, 0);
  console.log(`${product}: ${total} endpoints -> ${Object.keys(toolActions).length} tools (${destructiveReport.length} destructive actions)`);
  return { toolActions, destructiveReport };
}

const products = fs.readdirSync('src/products').filter((p) => fs.existsSync(`src/products/${p}/tool-map.json`));
const all = {};
for (const p of products) {
  const r = generate(p);
  if (r) all[p] = r;
}
if (process.argv.includes('--destructive')) {
  for (const [p, r] of Object.entries(all)) {
    console.log(`\n${p} destructive actions:\n  ` + r.destructiveReport.join('\n  '));
  }
}
